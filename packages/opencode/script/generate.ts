import path from "path"
import { fileURLToPath } from "url"

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const dir = path.resolve(__dirname, "..")

process.chdir(dir)

// Models are no longer bundled at build time. They are fetched on demand at runtime
// from models.dev (or OPENCODE_MODELS_URL), so the standalone build does not need
// network access to models.dev and users always get the latest provider catalog.
await Bun.write(
  path.join(dir, "../core/src/models-snapshot.js"),
  `// @ts-nocheck\n// Auto-generated by build.ts - do not edit\n// Intentionally empty: model/provider metadata is fetched at runtime.\nexport const snapshot = undefined\n`,
)
await Bun.write(
  path.join(dir, "../core/src/models-snapshot.d.ts"),
  `// Auto-generated by build.ts - do not edit\nexport declare const snapshot: undefined\n`,
)
console.log("Generated models-snapshot.js")
