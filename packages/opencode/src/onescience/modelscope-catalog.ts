export const modelScopeHubCacheDir = "modelscope/hub"

export const modelScopeModelsCacheDir = `${modelScopeHubCacheDir}/models`

export const modelScopeDatasetsCacheDir = `${modelScopeHubCacheDir}/datasets`

export function modelScopeModelId(title: string) {
  return modelScopeModels[title]
}

export function modelScopeDatasetId(itemId: string) {
  return modelScopeDatasets[itemId] ?? modelScopeDatasets[itemId.replace(/^seed-datasets-/, "")]
}

export function modelScopeDownloadModelCommand(modelId: string) {
  return `modelscope download --model ${modelId} --cache_dir ${modelScopeModelsCacheDir}`
}

export function modelScopeModelDownloadMethod(title: string) {
  const modelId = modelScopeModelId(title)
  if (!modelId) return undefined
  return modelScopeDownloadModelCommand(modelId)
}

export function modelScopeDownloadDatasetCommand(datasetId: string) {
  return `modelscope download --dataset ${datasetId} --cache_dir ${modelScopeDatasetsCacheDir}`
}

export function modelScopeDatasetDownloadMethod(itemId: string) {
  const datasetId = modelScopeDatasetId(itemId)
  if (!datasetId) return undefined
  return modelScopeDownloadDatasetCommand(datasetId)
}

